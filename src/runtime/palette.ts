export const PALETTE_NAMES: readonly string[] = [
  'black', 'dark-blue', 'dark-purple', 'dark-green', 'brown', 'dark-grey', 'light-grey', 'white',
  'red', 'orange', 'yellow', 'green', 'blue', 'lavender', 'pink', 'light-peach',
];

export const PALETTE_HEX: readonly string[] = PALETTE_RGB.map(
  ([r, g, b]) => '#' + [r, g, b].map((v) => v.toString(16).padStart(2, '0')).join(''),
);

/** Packed little-endian RGBA (for Uint32Array views on ImageData) of each palette entry. */
export const PALETTE_RGBA32: Uint32Array = Uint32Array.from(PALETTE_RGB, ([r, g, b]) => ((0xff << 24) | (b << 16) | (g << 8) | r) >>> 0);

/** Screen palette byte (0-15 or 128-143) -> PALETTE_* index. */
export function screenColorIndex(v: number): number {
  return (v & 0x80 ? 16 : 0) | (v & 0x0f);
}
